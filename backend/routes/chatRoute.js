const router = require("express").Router();
const controller = require("../controllers/chatController");
const auth = require("../middleware/authToken");
router.post("/save", auth, controller.saveChat);
router.get("/history", auth, controller.getHistory);
router.delete("/chats", auth, controller.deleteAllChats);
router.get("/chats/:sessionId", auth, controller.getChat);
router.patch("/chats/:sessionId", auth, controller.updateChat);
router.delete("/chats/:sessionId", auth, controller.deleteChat);
router.delete("/delete", auth, controller.deleteChat);
module.exports = router;
